from __future__ import annotations

import os
import pwd
import shlex
import shutil
import stat
import subprocess
import sys
import tempfile
from typing import Optional

from lib.apt_sources import ensure_debian_package_sources
from lib.system_utils import get_current_username
from lib.validation import validate_filesystem_path
from lib.validators import validate_username

BASE_PACKAGES = [
    "ca-certificates",
    "python3",
    "python3-venv",
    "curl",
    "git",
    "openssh-client",
    "rsync",
    "tar",
]

LAUNCHER_NAME = "basaltw"
TRANSITION_LAUNCHER_NAME = "infra-tools"
LEGACY_LAUNCHER_NAME = "infra_tools"
SYSTEM_LAUNCHER_DIR = "/usr/local/bin"
TMPFILES_CONF_PATH = "/etc/tmpfiles.d/infra_tools.conf"
QEMU_GUEST_AGENT_PACKAGE = "qemu-guest-agent"
QEMU_GUEST_AGENT_SERVICE = "qemu-guest-agent"


def _run_apt_command(command: list[str], env: dict[str, str], phase: str) -> int:
    """Run APT with inherited output and periodic progress while it waits."""

    process = subprocess.Popen(command, env=env)
    while process.poll() is None:
        try:
            process.wait(timeout=15)
        except subprocess.TimeoutExpired:
            print(
                f"{phase} is still running; waiting for APT or the network...",
                flush=True,
            )
    return process.returncode


def _resolve_project_script(script_path: str) -> str:
    """Return an absolute path to the project entry script for the launcher."""
    resolved = script_path
    if not os.path.isabs(resolved):
        resolved = shutil.which(resolved) or os.path.abspath(resolved)
    return resolved


def _launcher_contents(project_script: str) -> str:
    return (
        "#!/bin/sh\n"
        "# Auto-generated by Basaltwater bootstrap. Re-run "
        "`basaltw bootstrap` to refresh.\n"
        f"exec python3 {shlex.quote(project_script)} \"$@\"\n"
    )


def retire_legacy_launcher(target_dir: str) -> bool:
    """Remove the old launcher file from one configured launcher directory."""
    legacy_path = os.path.join(target_dir, LEGACY_LAUNCHER_NAME)
    if not os.path.lexists(legacy_path):
        return False
    if os.path.islink(legacy_path) or os.path.isfile(legacy_path):
        os.unlink(legacy_path)
        return True
    return False


def install_launcher(
    script_path: str,
    *,
    target_dir: str,
    chown_to: Optional[tuple[int, int]] = None,
) -> str:
    """Write the primary and v2 transition launchers into ``target_dir``.

    Returns the path of the launcher created. The launcher execs the project
    ``infra_tools.py`` with ``python3`` so users can run ``basaltw`` from
    any directory after bootstrap.
    """
    project_script = _resolve_project_script(script_path)
    if not os.path.isfile(project_script):
        raise ValueError(f"infra_tools script not found at {project_script}")
    validate_filesystem_path(project_script, must_exist=True)
    validate_filesystem_path(target_dir, must_exist=False)
    os.makedirs(target_dir, exist_ok=True)
    retire_legacy_launcher(target_dir)
    # Both wrappers invoke the retained module path directly. A source rollback
    # therefore keeps both usable, even when the old source predates basaltw.
    for name in (TRANSITION_LAUNCHER_NAME, LAUNCHER_NAME):
        _write_launcher(project_script, os.path.join(target_dir, name), chown_to)
    return os.path.join(target_dir, LAUNCHER_NAME)


def _write_launcher(
    project_script: str,
    launcher_path: str,
    chown_to: Optional[tuple[int, int]],
) -> None:
    file_descriptor, temporary_path = tempfile.mkstemp(
        prefix=".infra_tools_launcher.",
        dir=os.path.dirname(launcher_path),
        text=True,
    )
    try:
        with os.fdopen(file_descriptor, "w", encoding="utf-8") as handle:
            handle.write(_launcher_contents(project_script))
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(
            temporary_path,
            stat.S_IRUSR
            | stat.S_IWUSR
            | stat.S_IXUSR
            | stat.S_IRGRP
            | stat.S_IXGRP
            | stat.S_IROTH
            | stat.S_IXOTH,
        )
        if chown_to is not None:
            os.chown(temporary_path, chown_to[0], chown_to[1])
        os.replace(temporary_path, launcher_path)
    finally:
        if os.path.exists(temporary_path):
            os.unlink(temporary_path)


def resolve_bootstrap_user(requested_user: Optional[str]) -> tuple[str, str]:
    """Resolve the local user whose shell environment should be configured."""
    if requested_user:
        username = requested_user
    elif os.geteuid() == 0 and os.environ.get("SUDO_USER"):
        username = os.environ["SUDO_USER"]
    else:
        username = get_current_username()

    if not validate_username(username):
        raise ValueError(f"Invalid username: {username}")

    try:
        home_dir = pwd.getpwnam(username).pw_dir
    except KeyError as exc:
        raise ValueError(f"User not found: {username}") from exc

    return username, home_dir


def retire_legacy_tmpfiles_conf(
    conf_path: str = TMPFILES_CONF_PATH,
) -> bool:
    """Remove the ineffective legacy tmpfiles config from older bootstraps."""
    validate_filesystem_path(conf_path, must_exist=False)
    if not os.path.exists(conf_path):
        return False
    if os.geteuid() != 0:
        raise PermissionError(
            "Removing the legacy tmpfiles.d configuration requires root privileges."
        )
    os.unlink(conf_path)
    return True


def install_system_packages(
    shell: str,
    *,
    install_qemu_guest_agent: bool = False,
) -> int:
    """Install local system packages needed to operate infra-tools."""
    if os.geteuid() != 0:
        print("Error: System package installation requires root privileges. Re-run with sudo or use --skip-system-packages.")
        return 1

    if shutil.which("apt-get") is None:
        print("Error: automatic package installation requires apt-get on a Debian-based host.")
        return 1

    packages = list(BASE_PACKAGES)
    if shell == "bash":
        packages.append("bash-completion")
    if install_qemu_guest_agent:
        packages.append(QEMU_GUEST_AGENT_PACKAGE)

    try:
        ensure_debian_package_sources()
    except (OSError, RuntimeError, ValueError) as exc:
        print(f"Error: could not prepare Debian APT sources: {exc}")
        return 1

    print(
        "Refreshing package lists (APT may wait for another package operation)...",
        flush=True,
    )
    apt_environment = os.environ.copy()
    apt_environment["DEBIAN_FRONTEND"] = "noninteractive"
    update_command = [
        "apt-get",
        "-o",
        "DPkg::Lock::Timeout=120",
        "-o",
        "Dpkg::Use-Pty=0",
        "update",
        "-q",
    ]
    update_returncode = _run_apt_command(
        update_command,
        apt_environment,
        "APT package-list update",
    )
    if update_returncode != 0:
        print("Error: failed to update package lists; see the APT output above.")
        return 1

    print("Installing orchestration host packages...", flush=True)
    install_command = [
        "apt-get",
        "-o",
        "DPkg::Lock::Timeout=120",
        "-o",
        "Dpkg::Use-Pty=0",
        "install",
        "-y",
        "-q",
        *packages,
    ]
    install_returncode = _run_apt_command(
        install_command,
        apt_environment,
        "APT package installation",
    )
    if install_returncode != 0:
        print("Error: failed to install required packages; see the APT output above.")
        return 1

    print(f"✓ Installed system packages: {', '.join(packages)}", flush=True)

    if install_qemu_guest_agent:
        print("Starting and enabling qemu-guest-agent...", flush=True)
        service_result = subprocess.run(
            ["systemctl", "enable", "--now", QEMU_GUEST_AGENT_SERVICE],
            check=False,
        )
        if service_result.returncode != 0:
            print("Error: failed to start and enable qemu-guest-agent.")
            return 1
        print("✓ qemu-guest-agent is started and enabled", flush=True)

    return 0


def _resolve_self_command(script_path: str) -> list[str]:
    resolved_path = script_path
    if not os.path.isabs(resolved_path):
        resolved_path = shutil.which(resolved_path) or os.path.abspath(resolved_path)
    if resolved_path.endswith(".py"):
        return [sys.executable, resolved_path]
    return [resolved_path]


def run_orchestrator_bootstrap(
    script_path: str,
    shell: str,
    requested_user: Optional[str],
    skip_system_packages: bool = False,
    install_qemu_guest_agent: bool = False,
) -> int:
    """Bootstrap a local orchestration host for infra-tools administration."""
    from lib.cachyos import is_cachyos, bootstrap_cachyos

    if is_cachyos():
        return bootstrap_cachyos(script_path, shell, requested_user,
                                 skip_system_packages=skip_system_packages,
                                 install_qemu_guest_agent=install_qemu_guest_agent)
    try:
        username, home_dir = resolve_bootstrap_user(requested_user)
    except ValueError as exc:
        print(f"Error: {exc}")
        return 1

    if install_qemu_guest_agent and skip_system_packages:
        print(
            "Error: --qemu-guest-agent requires system package installation; "
            "remove --skip-system-packages."
        )
        return 1

    print(f"Bootstrapping orchestration host for {username}...")

    if not skip_system_packages:
        result = install_system_packages(
            shell,
            install_qemu_guest_agent=install_qemu_guest_agent,
        )
        if result != 0:
            return result
        try:
            launcher_path = install_launcher(script_path, target_dir=SYSTEM_LAUNCHER_DIR)
            print(f"✓ Installed system launcher: {launcher_path}")
        except (OSError, ValueError) as exc:
            print(f"Error: could not install system launcher in {SYSTEM_LAUNCHER_DIR}: {exc}")
            return 1
    else:
        try:
            if retire_legacy_launcher(SYSTEM_LAUNCHER_DIR):
                print(f"✓ Removed legacy system launcher: {SYSTEM_LAUNCHER_DIR}/{LEGACY_LAUNCHER_NAME}")
        except OSError as exc:
            print(f"Warning: could not remove legacy system launcher: {exc}")

    try:
        if retire_legacy_tmpfiles_conf():
            print(f"✓ Removed legacy systemd tmpfiles.d config: {TMPFILES_CONF_PATH}")
    except (OSError, PermissionError) as exc:
        print(f"Warning: could not remove legacy tmpfiles.d config: {exc}")

    command = _resolve_self_command(script_path) + [
        "python-tools",
        "--shell",
        shell,
        "--script-path",
        _resolve_project_script(script_path),
    ]
    current_username = get_current_username()
    if username == current_username:
        return subprocess.run(command, check=False).returncode

    if os.geteuid() != 0:
        print("Error: Switching to another user requires root privileges.")
        return 1

    env = os.environ.copy()
    env["HOME"] = home_dir
    env["USER"] = username
    return subprocess.run(
        ["runuser", "-u", username, "--", *command],
        env=env,
        check=False,
    ).returncode
